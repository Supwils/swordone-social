"""Which node module calls a given step -- the module a test must patch.

Each `graph/nodes_*.py` imports the steps its nodes call by name, and only
those (ruff's F401 refuses an unused import), so the ONE node module holding a
name is the one whose node looks it up at call time (S3 §12.15). Patching a
step anywhere else -- a re-export, a sibling -- changes nothing the graph
calls: a spy stays silent and an `explode` never fires. A name held by no node
module, or by several, is a test bug and raises instead of guessing.
"""

from __future__ import annotations

from types import ModuleType

from swil_agent.graph import nodes_act, nodes_dream, nodes_tail

NODE_MODULES: tuple[ModuleType, ...] = (nodes_act, nodes_dream, nodes_tail)


def caller_of(name: str) -> ModuleType:
    holders = [module for module in NODE_MODULES if name in vars(module)]
    if len(holders) != 1:
        found = [module.__name__ for module in holders]
        raise LookupError(f"{name!r} is held by {found}; expected exactly one node module")
    return holders[0]
